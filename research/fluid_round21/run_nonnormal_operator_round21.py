def _safe_state(g: pd.DataFrame) -> tuple[pd.DataFrame, pd.Series]:
    u_p = pd.to_numeric(g["perp_u"], errors="coerce")
    u_s = pd.to_numeric(g["spot_u"], errors="coerce")
    shear = base.causal_z(u_p - u_s)
    basis = base.causal_z(pd.to_numeric(g["basis_z"], errors="coerce"))
    source = (
        pd.to_numeric(g["oi_source_z"], errors="coerce").fillna(0.0)
        + 0.50 * pd.to_numeric(g["funding_change_z"], errors="coerce").fillna(0.0)
        + 0.25 * pd.to_numeric(g["quote_share_z"], errors="coerce").diff().fillna(0.0)
    )
    source = base.causal_z(source)
    perp_flow = pd.to_numeric(g["imb6_z"], errors="coerce")
    spot_flow = (
        2.0 * pd.to_numeric(g["taker_buy_quote_spot"], errors="coerce")
        / (pd.to_numeric(g["quote_volume_spot"], errors="coerce") + EPS)
        - 1.0
    )
    flow_gap = base.causal_z(perp_flow - base.causal_z(spot_flow.rolling(6, min_periods=6).mean()))
    pressure = base.causal_z(pd.to_numeric(g["pressure_gap"], errors="coerce"))
    state = pd.DataFrame(
        {
            "shear": shear,
            "basis": basis,
            "source": source,
            "flow_gap": flow_gap,
            "pressure": pressure,
        },
        index=g.index,
    )
    return state, source


def _fit_operator(history: np.ndarray) -> tuple[np.ndarray, np.ndarray, float, float, np.ndarray, np.ndarray] | None:
    # history is already strictly prior to the signal row. The last target is t-1.
    x0 = history[:-1]
    y0 = history[1:]
    mask = np.isfinite(x0).all(axis=1) & np.isfinite(y0).all(axis=1)
    if int(mask.sum()) < 300:
        return None
    x0 = x0[mask]
    y0 = y0[mask]
    center = np.nanmean(x0, axis=0)
    x = x0 - center
    y = y0 - center
    gram = x.T @ x + RIDGE * np.eye(x.shape[1])
    try:
        beta = np.linalg.solve(gram, x.T @ y)
    except np.linalg.LinAlgError:
        beta = np.linalg.pinv(gram) @ (x.T @ y)
    a = beta.T
    eigvals = np.linalg.eigvals(a)
    rho = float(np.max(np.abs(eigvals))) if eigvals.size else 0.0
    if not np.isfinite(rho):
        return None
    if rho > 0.995:
        a = a * (0.995 / rho)
        eigvals = np.linalg.eigvals(a)
        rho = float(np.max(np.abs(eigvals)))
    fro = float(np.linalg.norm(a, ord="fro"))
    eig_energy = float(np.sum(np.abs(eigvals) ** 2))
    henrici = math.sqrt(max(fro * fro - eig_energy, 0.0)) / (fro + EPS)
    skew = 0.5 * (a - a.T)
    return a, center, rho, henrici, eigvals, skew


def _operator_matrices(a: np.ndarray) -> dict[int, tuple[np.ndarray, np.ndarray]]:
    out: dict[int, tuple[np.ndarray, np.ndarray]] = {}
    power = np.eye(a.shape[0])
    cumulative = np.zeros_like(a)
    max_h = max(OPERATOR_HORIZONS)
    for step in range(1, max_h + 1):
        power = a @ power
        cumulative = cumulative + power
        if step in OPERATOR_HORIZONS:
            out[step] = (cumulative.copy(), power.copy())
    return out


def _slow_mode_value(a: np.ndarray, x: np.ndarray, horizon: int) -> float:
    try:
        vals, vecs = np.linalg.eig(a)
        idx = int(np.argmax(np.abs(vals)))
        inv = np.linalg.pinv(vecs)
        coeff = inv @ x.astype(complex)
        lam = complex(vals[idx])
        if abs(1.0 - lam) < 1e-8:
            scale = complex(float(horizon), 0.0)
        else:
            scale = lam * (1.0 - lam ** horizon) / (1.0 - lam)
        value = vecs[0, idx] * coeff[idx] * scale
        return float(np.real(value)) if np.isfinite(np.real(value)) else np.nan
    except Exception:  # noqa: BLE001
        return np.nan


def add_round21_mechanisms(group: pd.DataFrame) -> tuple[pd.DataFrame, dict[str, list[str]]]:
    g = group.sort_values("time").copy()
    state, source = _safe_state(g)
    values = state.to_numpy(dtype=float)
    n = len(g)
    raw_arrays = {name: np.full(n, np.nan, dtype=float) for names in FAMILY_RAW.values() for name in names}

    operator: np.ndarray | None = None
    center: np.ndarray | None = None
    matrices: dict[int, tuple[np.ndarray, np.ndarray]] = {}
    rho = np.nan
    henrici = np.nan
    skew: np.ndarray | None = None
    last_update = -10**9

    for i in range(n):
        if i >= WINDOW and (operator is None or i - last_update >= UPDATE_STEP):
            fitted = _fit_operator(values[i - WINDOW : i])
            if fitted is not None:
                operator, center, rho, henrici, _eigvals, skew = fitted
                matrices = _operator_matrices(operator)
                last_update = i
        if operator is None or center is None or skew is None or not matrices:
            continue
        current = values[i]
        if not np.isfinite(current).all():
            continue
        x = current - center
        norm_x = float(np.linalg.norm(x)) + EPS
        cumulative: dict[int, float] = {}
        transient: dict[int, float] = {}
        slow: dict[int, float] = {}
        source_only = np.zeros_like(x)
        source_only[2] = x[2]
        source_only[3] = x[3]
        pressure_only = np.zeros_like(x)
        pressure_only[1] = x[1]
        pressure_only[4] = x[4]

        for horizon in OPERATOR_HORIZONS:
            cmat, pmat = matrices[horizon]
            f = float((cmat @ x)[0] / math.sqrt(float(horizon)))
            cumulative[horizon] = f
            final = pmat @ x
            gain = float(np.linalg.norm(final) / norm_x)
            transient[horizon] = math.copysign(math.log1p(max(gain, 0.0)) * henrici, f) if f != 0.0 else 0.0
            slow[horizon] = _slow_mode_value(operator, x, horizon) / math.sqrt(float(horizon))

        raw_arrays["operator_cumulative_shear_h6"][i] = cumulative[6]
        raw_arrays["operator_cumulative_shear_h24"][i] = cumulative[24]
        raw_arrays["operator_cumulative_shear_h72"][i] = cumulative[72]
        raw_arrays["spectral_relaxation_shear_h24"][i] = cumulative[24] * max(1.0 - rho, 0.0)
        raw_arrays["nonnormal_shear_h24"][i] = cumulative[24] * henrici
        raw_arrays["nonnormal_shear_h72"][i] = cumulative[72] * henrici
        raw_arrays["transient_growth_direction_h24"][i] = transient[24]
        raw_arrays["transient_growth_direction_h72"][i] = transient[72]
        raw_arrays["operator_rotation_shear_h24"][i] = float((skew @ x)[0] * henrici)
        raw_arrays["source_impulse_shear_h24"][i] = float((matrices[24][0] @ source_only)[0] / math.sqrt(24.0))
        raw_arrays["source_impulse_shear_h72"][i] = float((matrices[72][0] @ source_only)[0] / math.sqrt(72.0))
        raw_arrays["pressure_impulse_shear_h24"][i] = float((matrices[24][0] @ pressure_only)[0] / math.sqrt(24.0))
        raw_arrays["pressure_impulse_shear_h72"][i] = float((matrices[72][0] @ pressure_only)[0] / math.sqrt(72.0))
        raw_arrays["slow_mode_shear_h24"][i] = slow[24]
        raw_arrays["slow_mode_shear_h72"][i] = slow[72]
        raw_arrays["slow_mode_source_alignment_h24"][i] = slow[24] * float(source.iloc[i])
        raw_arrays["slow_mode_source_alignment_h72"][i] = slow[72] * float(source.iloc[i])

    family_columns: dict[str, list[str]] = {}
    for family, raw_names in FAMILY_RAW.items():
        family_columns[family] = []
        for name in raw_names:
            raw_series = pd.Series(raw_arrays[name], index=g.index, dtype=float)
            normalized = base.causal_z(raw_series)
            g[name] = normalized
            family_columns[family].append(name)
            for span in STATE_SPANS:
                column = f"{name}_ewm{span}"
                g[column] = normalized.ewm(span=span, adjust=False, min_periods=span).mean()
                family_columns[family].append(column)
    return g, family_columns


